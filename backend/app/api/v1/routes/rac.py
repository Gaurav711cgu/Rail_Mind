@router.get("/quota-heatmap")
async def get_quota_heatmap(train_no: str, waitlist_pos: int):
    """Returns confirmation probability across all quotas for a given WL position."""
    quotas = [
        ("GN", "General"),
        ("TQ", "Tatkal"),
        ("LD", "Ladies"),
        ("SS", "Senior Citizen"),
        ("DF", "Defence"),
    ]
    results = []
    for code, label in quotas:
        prob, _, _ = rac_predictor.predict(
            {
                "waitlist_position": waitlist_pos,
                "rac_count": 15,
                "days_to_journey": 3,
                "quota": code,
                "cancellation_rate_route": 0.12,
                "recent_cancellations_24h": 5,
            }
        )
        results.append(
            {
                "quota": f"{code} ({label})",
                "probability": round(prob, 3),
                "description": label,
            }
        )
    return results


